/**
 * Canonical feature schema v2: "hand_body_face".
 *
 * This is the TypeScript twin of ml_service/feature_schema.py. A Python
 * module can't run in a browser, so the constants and logic are
 * re-expressed here -- but every constant and every function's behavior
 * must match the Python side exactly. This is enforced, not just hoped
 * for: `npm run schema:crosscheck` (see package.json) runs
 * featureSchema.crosscheck.test.ts, which feeds the SAME synthetic
 * landmark fixture (frontend/src/lib/__tests__/crosscheckFixture.json)
 * through this file's buildFeatureVector()/normalizeSequence() and
 * compares the result byte-for-byte against a vector generated by the
 * Python module (ml_service/tests/test_feature_schema.py generates that
 * fixture's expected output -- see "Cross-language golden vector" in
 * FEATURE_SCHEMA.md for exactly how the two are kept in sync).
 *
 * See feature_schema.py's docstring for the full rationale (Holistic vs.
 * separate detectors, why face is a reduced subset not the full mesh, why
 * pose visibility is excluded from z-scoring, etc.) -- it isn't repeated
 * here to avoid the two docs drifting apart; FEATURE_SCHEMA.md is the
 * canonical prose write-up both files point to.
 */

