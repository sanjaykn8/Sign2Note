export const FEATURE_DIM = 2 * HAND_FEATURE_DIM + POSE_FEATURE_DIM + FACE_FEATURE_DIM; // 285

const POSE_START = FEATURE_GROUPS[2][1];
export const POSE_VISIBILITY_INDICES = POSE_LANDMARK_INDICES.map((_, i) => POSE_START + 4 * i + 3);

export class FeatureSchemaError extends Error {}

export function assertFeatureDim(dim: number, context = ""): void {
  if (dim !== FEATURE_DIM) {
    const where = context ? ` (${context})` : "";
    const hint = dim === 126 ? " These look like old hand-only features (schema v1, 126 dims)." : "";
    throw new FeatureSchemaError(
      `Feature dimension mismatch${where}: got ${dim}, but the current feature schema is ` +
        `v${FEATURE_SCHEMA_VERSION} ('${FEATURE_TYPE}'), which expects ${FEATURE_DIM} dims per frame ` +
        `(${HAND_FEATURE_DIM} left hand + ${HAND_FEATURE_DIM} right hand + ${POSE_FEATURE_DIM} pose + ` +
        `${FACE_FEATURE_DIM} face).${hint} Re-run feature extraction, or reload a schema-v2-compatible model.`
    );
  }
}

// ---------------------------------------------------------------------------
// build one frame's feature vector
// ---------------------------------------------------------------------------

function flattenHand(landmarks: Landmark[] | null | undefined): Float32Array {
  const out = new Float32Array(HAND_FEATURE_DIM);
  if (!landmarks) return out;
  for (let i = 0; i < NUM_HAND_LANDMARKS && i < landmarks.length; i++) {
    out[i * 3] = landmarks[i].x;
    out[i * 3 + 1] = landmarks[i].y;
    out[i * 3 + 2] = landmarks[i].z;
  }
  return out;
}

function flattenSubset(
  landmarks: Landmark[] | null | undefined,
  indices: number[],
  dimsPerLandmark: number,
  includeVisibility: boolean
): Float32Array {
  const out = new Float32Array(indices.length * dimsPerLandmark);
  if (!landmarks) return out;
  for (let slot = 0; slot < indices.length; slot++) {
    const srcIdx = indices[slot];
    if (srcIdx >= landmarks.length) continue; // defensive: leave as zeros
    const lm = landmarks[srcIdx];
    const base = slot * dimsPerLandmark;
    out[base] = lm.x;
    out[base + 1] = lm.y;
    out[base + 2] = lm.z;
    if (includeVisibility) out[base + 3] = lm.visibility ?? 0;
  }
  return out;
}

/**
 * Build one canonical FEATURE_DIM-length vector for a single frame from
 * a HolisticLandmarker result's four landmark lists (already unwrapped to
 * the single tracked instance -- e.g. `result.leftHandLandmarks[0]`, not
 * the raw `NormalizedLandmark[][]`). Mirrors feature_schema.py's
 * build_feature_vector() exactly.
 */
export function buildFeatureVector(
  leftHand: Landmark[] | null | undefined,
  rightHand: Landmark[] | null | undefined,
  pose: Landmark[] | null | undefined,
  face: Landmark[] | null | undefined
): Float32Array {
  const left = flattenHand(leftHand);
  const right = flattenHand(rightHand);
  const poseVec = flattenSubset(pose, POSE_LANDMARK_INDICES, POSE_DIMS_PER_LANDMARK, true);
  const faceVec = flattenSubset(face, FACE_LANDMARK_INDICES, FACE_DIMS_PER_LANDMARK, false);

  const out = new Float32Array(FEATURE_DIM);
  out.set(left, 0);
  out.set(right, HAND_FEATURE_DIM);
  out.set(poseVec, 2 * HAND_FEATURE_DIM);
  out.set(faceVec, 2 * HAND_FEATURE_DIM + POSE_FEATURE_DIM);
  return out;
}

// ---------------------------------------------------------------------------
// Normalization -- mirrors feature_schema.py's normalize_sequence()/
// pad_or_trim()/prepare_window() exactly (including the pose-visibility
// exclusion and the trim-then-normalize-then-pad ordering).
// ---------------------------------------------------------------------------

const POSE_VIS_SET = new Set(POSE_VISIBILITY_INDICES);

/**
 * Per-dimension z-score over time (axis 0), excluding pose-visibility
 * dims (passed through, clipped to [0, 1]). `window` is a flat Float32Array
 * of length frames*dims (row-major: frame 0's `dims` values, then frame
 * 1's, ...) -- same convention the existing normalizeWindow() used, kept
 * so KeypointBuffer doesn't need a data-layout change.
 */
export function normalizeSequence(window: Float32Array, frames: number, dims = FEATURE_DIM): Float32Array {
  const mean = new Float64Array(dims);
  const std = new Float64Array(dims);
  for (let f = 0; f < frames; f++) {
    for (let d = 0; d < dims; d++) mean[d] += window[f * dims + d];
  }
  for (let d = 0; d < dims; d++) mean[d] /= frames;

  for (let f = 0; f < frames; f++) {
    for (let d = 0; d < dims; d++) {
      const diff = window[f * dims + d] - mean[d];
      std[d] += diff * diff;
    }
  }
  for (let d = 0; d < dims; d++) std[d] = Math.sqrt(std[d] / frames) + 1e-5;

  const out = new Float32Array(frames * dims);
  const excludeVisibility = dims === FEATURE_DIM;
  for (let f = 0; f < frames; f++) {
    for (let d = 0; d < dims; d++) {
      const raw = window[f * dims + d];
      if (excludeVisibility && POSE_VIS_SET.has(d)) {
        out[f * dims + d] = Math.min(1, Math.max(0, raw));
      } else {
        out[f * dims + d] = (raw - mean[d]) / std[d];
      }
    }
  }
  return out;
}
