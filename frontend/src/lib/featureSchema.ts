function flattenGroups(groups: Record<string, Record<string, number>>): { names: string[]; indices: number[] } {
  const names: string[] = [];
  const indices: number[] = [];
  for (const group of Object.values(groups)) {
    for (const [name, idx] of Object.entries(group)) {
      names.push(name);
      indices.push(idx);
    }
  }
  return { names, indices };
}

