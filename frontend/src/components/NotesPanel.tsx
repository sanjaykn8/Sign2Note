import { useEffect, useState } from "react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { FileText, Pencil, Check, X, RefreshCw, Download } from "lucide-react";
import { renderMarkdown } from "@/lib/markdown";
import { downloadMarkdown, downloadPlainText, downloadPdf, downloadDocx, exportFilename } from "@/lib/notesExport";
import type { GenerationMeta } from "@/lib/api";

interface NotesPanelProps {
  /** The generated Markdown. When this prop changes (e.g. after a
   * regenerate), the panel's editable copy re-syncs to it. */
  markdown: string;
  title?: string;
  durationSeconds?: number;
  onRegenerate?: () => void;
  regenerating?: boolean;
  /** Which generator produced `markdown` (LLM or deterministic fallback). */
  generation?: GenerationMeta;
}

type ExportFormat = "md" | "txt" | "pdf" | "docx";

/**
 * Preview -> Edit -> Export. Every export uses the text currently shown
 * (including the user's edits) -- nothing is regenerated or reinterpreted
 * at export time.
 */
export default function NotesPanel({ markdown, title = "Lecture Notes", durationSeconds, onRegenerate, regenerating, generation }: NotesPanelProps) {
  const [current, setCurrent] = useState(markdown);
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(markdown);
  const [exportBusy, setExportBusy] = useState<ExportFormat | null>(null);
  const [exportError, setExportError] = useState<string | null>(null);

  // Re-sync when the parent hands us freshly (re)generated notes.
  useEffect(() => {
    setCurrent(markdown);
    setDraft(markdown);
    setEditing(false);
  }, [markdown]);

  const saveEdit = () => {
    setCurrent(draft);
    setEditing(false);
  };
  const cancelEdit = () => {
    setDraft(current);
    setEditing(false);
  };

  const handleExport = async (format: ExportFormat) => {
    setExportBusy(format);
    setExportError(null);
    // Export what is on screen: if the user is mid-edit, the visible text
    // is the draft.
    const text = editing ? draft : current;
    try {
      const name = exportFilename(title, format);
      if (format === "md") downloadMarkdown(name, text);
      else if (format === "txt") downloadPlainText(name, text, { title, durationSeconds });
      else if (format === "pdf") await downloadPdf(name, text, { title, durationSeconds });
      else await downloadDocx(name, text, { title, durationSeconds });
    } catch (err) {
      setExportError(err instanceof Error ? err.message : `Couldn't generate the ${format.toUpperCase()}.`);
    } finally {
      setExportBusy(null);
    }
  };

  return (
    <Card>
      <CardHeader className="pb-3 flex flex-row flex-wrap items-center justify-between gap-2">
        <CardTitle className="flex flex-wrap items-center gap-2 text-base">
          <FileText className="h-5 w-5 text-primary" aria-hidden />
          {title}
          {generation && (
            <Badge
              variant="outline"
              className={`text-xs font-normal ${generation.generator === "llm" ? "" : "text-amber-700 border-amber-500/40"}`}
              title={generation.fallback_reason ?? undefined}
            >
              {generation.generator === "llm"
                ? `Generated by local LLM${generation.llm_model ? ` (${generation.llm_model})` : ""}`
                : generation.fallback_reason
                  ? "LLM unavailable — deterministic fallback used"
                  : "Deterministic notes (no LLM)"}
            </Badge>
          )}
        </CardTitle>
        <div className="flex flex-wrap gap-2">
          {!editing ? (
            <Button size="sm" variant="outline" onClick={() => setEditing(true)}>
              <Pencil className="h-3.5 w-3.5 mr-1.5" aria-hidden />
              Edit
            </Button>
          ) : (
            <>
              <Button size="sm" variant="outline" onClick={cancelEdit}>
                <X className="h-3.5 w-3.5 mr-1.5" aria-hidden />
                Cancel
              </Button>
              <Button size="sm" onClick={saveEdit}>
                <Check className="h-3.5 w-3.5 mr-1.5" aria-hidden />
                Save
              </Button>
            </>
          )}
          {onRegenerate && (
            <Button size="sm" variant="outline" onClick={onRegenerate} disabled={regenerating}>
              <RefreshCw className={`h-3.5 w-3.5 mr-1.5 ${regenerating ? "animate-spin" : ""}`} aria-hidden />
              {regenerating ? "Regenerating…" : "Regenerate"}
            </Button>
          )}
        </div>
      </CardHeader>
      <CardContent className="space-y-4">
        {editing ? (
          <textarea
            value={draft}
            onChange={(e) => setDraft(e.target.value)}
            rows={14}
            aria-label={`Edit ${title}`}
            className="w-full rounded-lg border bg-background px-3 py-2 text-sm font-mono leading-relaxed focus:outline-none focus:ring-2 focus:ring-ring"
            autoFocus
          />
        ) : (
          <div
            className="prose prose-sm max-w-none text-foreground leading-relaxed break-words"
            dangerouslySetInnerHTML={{ __html: renderMarkdown(current) }}
          />
        )}

        <div className="flex flex-wrap items-center gap-2 border-t border-border pt-3" role="group" aria-label="Export">
          <span className="text-xs font-medium text-muted-foreground mr-1">Export:</span>
          {(
            [
              ["md", "Markdown"],
              ["txt", "Text"],
              ["pdf", "PDF"],
              ["docx", "Word (.docx)"],
            ] as [ExportFormat, string][]
          ).map(([fmt, label]) => (
            <Button key={fmt} size="sm" variant="secondary" onClick={() => handleExport(fmt)} disabled={exportBusy !== null}>
              <Download className="h-3.5 w-3.5 mr-1.5" aria-hidden />
              {exportBusy === fmt ? "Preparing…" : label}
            </Button>
          ))}
        </div>
        {exportError && (
          <p className="text-xs text-destructive" role="alert">
            {exportError}
          </p>
        )}
      </CardContent>
    </Card>
  );
}
